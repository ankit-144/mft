// TestMixedSeriesMatchesGolden is the literal golden: a fixed, irregular price
// path with hand-checkable bars, compared value by value against features
// derived independently from the contract.
func TestMixedSeriesMatchesGolden(t *testing.T) {
	b := NewBuilder(tradingZone(t))
	table, err := b.Build(mixedCandles())
	if err != nil {
		t.Fatalf("Build: %v", err)
	}

	for _, i := range slices.Sorted(maps.Keys(mixedGolden)) {
		want := mixedGolden[i]
		if len(table.Columns) != len(want) {
			t.Fatalf("golden row has %d values but the table has %d columns", len(want), len(table.Columns))
		}
		for j, w := range want {
			assertClose(t, table.Rows[i][j], w, fmt.Sprintf("row %d %s", i, table.Columns[j]))
		}
	}
}

// TestMixedFixtureDegenerateRows spells out what three of the golden rows are
// for. The golden pins their values; this pins their meaning, so a future
// change to the policy cannot quietly redefine them.
func TestMixedFixtureDegenerateRows(t *testing.T) {
	b := NewBuilder(tradingZone(t))
	table, err := b.Build(mixedCandles())
	if err != nil {
		t.Fatalf("Build: %v", err)
	}

	const (
		doji        = 25 // high == low == close
		noVolume    = 33 // volume 0
		flatReturns = 39 // 20 flat closes behind it
	)

	t.Run("a doji has no range to measure", func(t *testing.T) {
		for _, name := range []string{"range_1", "body_1", "upper_wick_1", "lower_wick_1", "spread_proxy"} {
			if got := col(t, table, doji, name); got != 0 {
				t.Errorf("%s = %v on a doji, want 0", name, got)
			}
		}
	})

	t.Run("a bar that never traded", func(t *testing.T) {
		for _, name := range []string{"spread_proxy", "volume_ratio"} {
			if got := col(t, table, noVolume, name); got != 0 {
				t.Errorf("%s = %v on a zero-volume bar, want 0", name, got)
			}
		}
		// The zero volume still moves the z-score: it is far below the window
		// it is measured against.
		if got := col(t, table, noVolume, "volume_z_20"); got >= 0 {
			t.Errorf("volume_z_20 = %v on a zero-volume bar, want a negative z-score", got)
		}
	})

	t.Run("a window with no dispersion", func(t *testing.T) {
		for _, name := range []string{"vol_5", "vol_20", "vol_ratio", "momentum_rsi_14"} {
			if got := col(t, table, flatReturns, name); got != 0 {
				t.Errorf("%s = %v on a 20-bar flat window, want 0", name, got)
			}
		}
		// sma_gap_10 is zero too, but only to within the rounding of summing
		// ten copies of the same price and dividing by ten.
		assertClose(t, col(t, table, flatReturns, "sma_gap_10"), 0, "sma_gap_10 on a flat window")
	})

	t.Run("the warm-up boundary", func(t *testing.T) {
		if got := col(t, table, WarmupRows-1, "ret_60"); got != 0 {
			t.Errorf("ret_60 = %v on row %d, want 0: no row before the warm-up is a target", got, WarmupRows-1)
		}
		if !IsWarmup(WarmupRows - 1) {
			t.Error("row WarmupRows-1 must be a warm-up row")
		}
		if IsWarmup(WarmupRows) {
			t.Error("row WarmupRows must be a prediction target")
		}
	})
}
