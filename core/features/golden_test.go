// mixedCandles materialises the fixture as a candle window.
func mixedCandles() []contracts.Candle {
	out := make([]contracts.Candle, len(mixedBars))
	for i, b := range mixedBars {
		out[i] = contracts.Candle{
			Symbol:    "RELIANCE",
			Timestamp: mixedFixtureStart.Add(time.Duration(b.minute) * time.Minute),
			Open:      b.open,
			High:      b.high,
			Low:       b.low,
			Close:     b.close,
			Volume:    b.volume,
		}
	}
	return out
}

